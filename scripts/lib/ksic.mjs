// induty_code -> { sec, secDiv, secDivName }.
// 알 수 없는 중분류(표에 없는 2자리)는 secDivName을 붙이지 않는다 — "기타"로
// 뭉뚱그리면 분류표가 개정돼 새 중분류가 생겼을 때 아무도 눈치채지 못한다.
export function resolveSector(indutyCode) {
  const code = String(indutyCode || "").trim();
  if (!/^\d{2,5}$/.test(code)) return null;
  const div = code.slice(0, 2);
  const divName = KSIC_DIVISIONS[div];
  return { sec: code, secDiv: div, ...(divName ? { secDivName: divName } : {}) };
}
